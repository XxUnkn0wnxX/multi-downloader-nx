import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import YAML from 'yaml';

export type CrunchySessionSlot = 'androidtv' | 'android' | 'web' | 'legacy';
export type CrunchySession = Record<string, any>;

type Store = {
	active?: CrunchySessionSlot;
	sessions: Partial<Record<CrunchySessionSlot, CrunchySession>>;
};

const slots: readonly CrunchySessionSlot[] = ['androidtv', 'android', 'web', 'legacy'];

function isRecord(value: unknown): value is Record<string, unknown> {
	return value !== null && typeof value === 'object' && !Array.isArray(value);
}

export function crunchySessionSlot(session: CrunchySession): CrunchySessionSlot {
	switch (session.auth_type) {
		case 'device':
			return 'androidtv';
		case 'android':
			return 'android';
		case 'web':
			return 'web';
		default:
			return 'legacy';
	}
}

function parseStore(text: string): Store {
	const data: unknown = YAML.parse(text);
	if (data === null) return { sessions: {} };
	if (!isRecord(data)) throw new Error('Invalid Crunchyroll session file');
	if (!('version' in data) && !('sessions' in data)) {
		if (!Object.keys(data).length) return { sessions: {} };
		const slot = crunchySessionSlot(data);
		return { active: slot, sessions: { [slot]: data } };
	}
	if (data.version !== 1 || !isRecord(data.sessions) || Object.keys(data.sessions).some((slot) => !slots.includes(slot as CrunchySessionSlot))) {
		throw new Error('Unsupported Crunchyroll session file');
	}
	const sessions: Store['sessions'] = {};
	for (const slot of slots) {
		const session = data.sessions[slot];
		if (session === undefined) continue;
		if (!isRecord(session)) throw new Error('Invalid Crunchyroll session block');
		if (!Object.keys(session).length) continue;
		if (crunchySessionSlot(session) !== slot) throw new Error('Mismatched Crunchyroll session block');
		sessions[slot] = session;
	}
	const active = data.active as CrunchySessionSlot | undefined;
	return { active: active && slots.includes(active) && sessions[active] ? active : slots.find((slot) => sessions[slot]), sessions };
}

export function loadCrunchySessions(file: string): Store {
	try {
		return parseStore(fs.readFileSync(file, 'utf8'));
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code === 'ENOENT') return { sessions: {} };
		throw error;
	}
}

function serializeStore(store: Store): string {
	const header = '# This file is automatically generated and updated by Multi Downloader NX. Do not edit it manually.\n';
	const root = YAML.stringify({ version: 1, active: store.active ?? null });
	const blocks = slots
		.filter((slot) => slot !== 'legacy' || store.sessions.legacy)
		.map((slot) => {
			const block = YAML.stringify({ [slot]: store.sessions[slot] ?? {} })
				.trimEnd()
				.replace(/^/gm, '  ');
			return `  ### ${slot} ###\n${block}\n`;
		});
	return `${header}${root}sessions:\n${blocks.join('\n')}`;
}

export function saveCrunchySession(file: string, session: CrunchySession, options: { activate?: boolean; expectedRefresh?: string } = {}): boolean {
	let lock: number | undefined;
	let temporary: string | undefined;
	const lockFile = `${file}.lock`;
	try {
		fs.mkdirSync(path.dirname(file), { recursive: true });
		lock = fs.openSync(lockFile, 'wx', 0o600);
		const store = loadCrunchySessions(file);
		const slot = crunchySessionSlot(session);
		if (options.expectedRefresh !== undefined && store.sessions[slot]?.refresh_token !== options.expectedRefresh) return false;
		store.sessions[slot] = session;
		if (options.activate !== false || !store.active) store.active = slot;
		const next = `${file}.${randomUUID()}.tmp`;
		const fd = fs.openSync(next, 'wx', 0o600);
		temporary = next;
		try {
			fs.writeFileSync(fd, serializeStore(store));
			fs.fsyncSync(fd);
		} finally {
			fs.closeSync(fd);
		}
		fs.renameSync(next, file);
		return true;
	} catch {
		return false;
	} finally {
		if (temporary) {
			try {
				fs.unlinkSync(temporary);
			} catch {
				/* Renamed or already removed. */
			}
		}
		if (lock !== undefined) {
			try {
				fs.closeSync(lock);
			} catch {
				/* The lock file is still ours. */
			}
			try {
				fs.unlinkSync(lockFile);
			} catch {
				/* A later write will report a lock failure. */
			}
		}
	}
}

export async function withCrunchyRefreshLock<T>(file: string, slot: CrunchySessionSlot, refresh: () => Promise<T>): Promise<T | undefined> {
	const lockFile = `${file}.${slot}.lock`;
	let lock: number;
	try {
		fs.mkdirSync(path.dirname(file), { recursive: true });
		lock = fs.openSync(lockFile, 'wx', 0o600);
	} catch {
		return;
	}
	try {
		return await refresh();
	} finally {
		try {
			fs.closeSync(lock);
		} finally {
			fs.unlinkSync(lockFile);
		}
	}
}
